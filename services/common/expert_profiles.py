def _extract_json(text: str) -> Optional[dict]:
    match = re.search(r"\{.*\}", text or "", re.S)
    if not match:
        return None
    try:
        data = json.loads(match.group(0))
    except (ValueError, TypeError):
        return None
    return data if isinstance(data, dict) else None


def _clean_profile(raw: object) -> Optional[Dict[str, List[str]]]:
    if not isinstance(raw, dict):
        return None
    profile: Dict[str, List[str]] = {}
    for field in ("skills", "knowledge", "experience", "method"):
        value = raw.get(field)
        if isinstance(value, str):
            value = [value]
        if not isinstance(value, list):
            continue
        items = [re.sub(r"\s+", " ", str(v)).strip()[:300] for v in value if str(v).strip()]
        if items:
            profile[field] = items[:8]
    return profile if profile.get("skills") else None


async def discover_competencies(
    role_keys: Iterable[str], *, force: bool = False
) -> Dict[str, Dict[str, List[str]]]:
    """Шаг 1: спрашиваем ИИ, чем обладает специалист. Резерв — встроенные профили."""
    keys = [k for k in role_keys if k in ROLES]
    result: Dict[str, Dict[str, List[str]]] = {}
    missing: List[str] = []
    for key in keys:
        cached = None if force else _cache.get(key, PROFILE_TTL_SEC)
        profile = _clean_profile(cached)
        if profile:
            result[key] = profile
        else:
            missing.append(key)
    if missing:
        roles_text = "\n".join(
            f'- "{k}": {ROLES[k]["title"]} — {ROLES[k]["scope"]}' for k in missing
        )
        prompt = (
            "Для бизнеса: бренд YaSoKo — моделирующие гели, базы и топы для ногтей (банки 15 г), производство в "
            "г. Иваново, продажи на Ozon и Wildberries, ИП на УСН 6% (доходы).\n"
            "Ответь на вопрос: какими НАВЫКАМИ, ЗНАНИЯМИ и ОПЫТОМ обладает каждый специалист ниже, чтобы давать "
            "не общие советы, а полный расчёт с аргументацией? Включи знание конкретных разделов и кнопок личных "
            "кабинетов Ozon и Wildberries и схем рекламы, актуальных на 20.11.2026. Если не уверен в названии "
            "кнопки — так и укажи.\n\n"
            f"СПЕЦИАЛИСТЫ:\n{roles_text}\n\n"
            "Верни ТОЛЬКО JSON без пояснений вида:\n"
            '{"<ключ роли>": {"skills": ["..."], "knowledge": ["..."], "experience": ["..."], '
            '"method": ["как принимает решение, какие формулы использует"]}}\n'
            "По 3–6 коротких пунктов в каждом списке, с конкретикой (формулы, названия разделов ЛК)."
        )
        data: Optional[dict] = None
        try:
            text, _ = await generate(prompt, max_tokens=4096, temperature=0.2, timeout=60)
            data = _extract_json(text)
        except Exception as exc:  # noqa: BLE001 — резерв сработает автоматически
            logger.warning("Профили специалистов: ИИ недоступен (%s), берём встроенные", exc)
        for key in missing:
            profile = _clean_profile((data or {}).get(key))
            if profile:
                _cache.put(key, profile)
            else:
                profile = FALLBACK_PROFILES.get(key) or {"skills": ["расчёт и аргументация по данным отчёта"]}
            result[key] = profile
    return result


def render_competencies(competencies: Dict[str, Dict[str, List[str]]]) -> str:
    blocks = []
    for key, profile in competencies.items():
        lines = [f"■ {ROLES[key]['title']}:"]
        for field, label in (
            ("skills", "Навыки"),
            ("knowledge", "Знания (ЛК, схемы)"),
            ("experience", "Опыт"),
            ("method", "Метод принятия решений"),
        ):
            if profile.get(field):
                lines.append(f"  {label}: " + "; ".join(profile[field]))
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


async def build_expert_preamble(role_keys: Iterable[str], *, with_cabinets: bool = True) -> str:
    """Готовый блок для промпта: компетенции + обязательный метод (+ схемы ЛК)."""
    competencies = await discover_competencies(role_keys)
    parts = [
        "ПРОФИЛИ СПЕЦИАЛИСТОВ (отвечай строго с позиции этих навыков, знаний и опыта, "
        "применяй их методы, а не общие фразы):",
        render_competencies(competencies),
        METHOD_RULES,
    ]
    if with_cabinets:
        parts.append(CABINET_SCHEMES)
    return "\n".join(parts)
